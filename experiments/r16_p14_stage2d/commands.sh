#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
PYTHON_BIN="${PYTHON_BIN:-/mnt/cpfs/zbl-cpfs-new/USERS/leon/envs/libero_sim/bin/python}"
export PYTHONPATH="${REPO_ROOT}/experiments/r16_p14_stage2d:${REPO_ROOT}/experiments/r16_p14_stage2c:${REPO_ROOT}/experiments/r16_p14_stage2b:${REPO_ROOT}/experiments/r16_p14_stage2a:${REPO_ROOT}/experiments/r16_p14_libero_stage1:${PYTHONPATH:-}"
export MUJOCO_GL="${MUJOCO_GL:-egl}"
export PYOPENGL_PLATFORM="${PYOPENGL_PLATFORM:-egl}"

# The source freeze and init pool are immutable inputs and are intentionally
# not regenerated by this resumable formal runner. Run the numbered phases in
# order, committing each barrier before the next phase so the implementation's
# read-before-commit guards remain effective.
case "${1:-}" in
  phase1)
    "${PYTHON_BIN}" -m r16_p14_stage2d.events --consolidate --consolidate-splits calibration,evaluation
    "${PYTHON_BIN}" -m r16_p14_stage2d.qualification --consolidate
    "${PYTHON_BIN}" -m r16_p14_stage2d.cohort
    ;;
  checkpoint-barrier)
    "${PYTHON_BIN}" -m r16_p14_stage2d.checkpoint_barrier
    ;;
  atlas)
    "${PYTHON_BIN}" -m r16_p14_stage2d.calibration --consolidate
    ;;
  freeze-rule)
    "${PYTHON_BIN}" -m r16_p14_stage2d.freeze_rule
    ;;
  phase2)
    "${PYTHON_BIN}" -m r16_p14_stage2d.confirmatory --consolidate
    "${PYTHON_BIN}" -m r16_p14_stage2d.statistics --primary
    "${PYTHON_BIN}" -m r16_p14_stage2d.mechanism_reverse
    ;;
  phase3)
    "${PYTHON_BIN}" -m r16_p14_stage2d.oracle_appendix --consolidate
    "${PYTHON_BIN}" -m r16_p14_stage2d.mechanism_reverse
    "${PYTHON_BIN}" -m r16_p14_stage2d.report
    "${PYTHON_BIN}" -m r16_p14_stage2d.checksums
    "${PYTHON_BIN}" -m pytest -q "${REPO_ROOT}/experiments/r16_p14_stage2d/tests"
    ;;
  *)
    printf 'usage: %s {phase1|checkpoint-barrier|atlas|freeze-rule|phase2|phase3}\n' "$0" >&2
    exit 64
    ;;
esac
